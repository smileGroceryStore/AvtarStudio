import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:400,height:560}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{const Native=window.WebSocket;window.testSockets=[];window.WebSocket=class extends Native{constructor(...a){super(...a);window.testSockets.push(this);}}});
await page.request.post('http://127.0.0.1:8098/api/control',{data:{action:'settings',settings:{avatarMode:'2d',petColor:'mint'}}});
await page.goto('http://127.0.0.1:8098/widget');
await page.waitForSelector('.avatar-2d:not([hidden])');
await page.waitForTimeout(700);
await page.screenshot({path:'test-results/2d-widget.png',omitBackground:true});
assert.equal(await page.locator('#c').isVisible(),false);
const before=await page.locator('#pet-head').getAttribute('transform');
await page.evaluate(()=>{const socket=window.testSockets[0],handler=socket.onmessage;socket.onmessage=e=>{if(!e.isTrusted)handler(e);};});
await page.evaluate(async()=>{const state=await(await fetch('/api/state')).json();state.rig={head:[.2,.3,.25],expressions:{aa:1,blinkLeft:1},pose:{armDirections:{leftUpperArm:[-.8,.2,0]}}};window.injectRig=setInterval(()=>window.testSockets[0].dispatchEvent(new MessageEvent('message',{data:JSON.stringify(state)})),10);});
await page.waitForTimeout(700);
assert.notEqual(await page.locator('#pet-head').getAttribute('transform'),before);
assert.ok(Number(await page.locator('#pet-mouth').getAttribute('ry'))>8);
assert.ok((await page.locator('#pet-arm-left .forearm').getAttribute('d')).includes(' L'));
assert.equal(await page.locator('#pet-arm-left').getAttribute('data-layer'),'front');
await page.evaluate(async()=>{
 clearInterval(window.injectRig);const state=await(await fetch('/api/state')).json();
 window.depthState=state;state.rig={pose:{armPoints:{left:{points:[[.2,0,0],[.25,-.22,.02],[.05,-.1,.25]],shoulderSpan:.4}}}};
 window.injectRig=setInterval(()=>window.testSockets[0].dispatchEvent(new MessageEvent('message',{data:JSON.stringify(window.depthState)})),10);
});
await page.waitForTimeout(600);
assert.equal(await page.locator('#pet-arm-left').getAttribute('data-layer'),'front');
assert.equal(await page.locator('#pet-arms-front > #pet-arm-left').count(),1);
await page.evaluate(()=>{window.depthState.rig.pose.armPoints.left.points[2][2]=-.25;});
await page.waitForTimeout(600);
assert.equal(await page.locator('#pet-arms-back > #pet-arm-left').count(),1);
await page.evaluate(()=>{window.depthState.rig.pose.armPoints.left.points[2][2]=.25;});
await page.waitForTimeout(600);
assert.equal(await page.locator('#pet-arms-front > #pet-arm-left').count(),1);
await page.goto('http://127.0.0.1:8098/');
await page.selectOption('#avatarMode','3d');await page.waitForTimeout(600);
assert.equal(await page.locator('#c').isVisible(),true);
await page.selectOption('#avatarMode','2d');await page.selectOption('#petColor','rose');await page.waitForTimeout(700);
await page.reload();await page.waitForSelector('.avatar-2d:not([hidden])');
assert.equal(await page.locator('#petColor').inputValue(),'rose');
assert.deepEqual(errors,[]);
await browser.close();console.log('2D widget, mode switching, saved color, no browser errors: PASS');
