import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
await fs.mkdir('test-results',{recursive:true});
const base=process.env.AVATAR_TEST_URL || 'http://127.0.0.1:8080';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
await page.goto(base+'/?desktop=1');
await page.locator('#modelStatus').filter({hasText:'已加载'}).waitFor({timeout:60000});
assert.equal(await page.locator('html').evaluate(el=>el.classList.contains('desktop-mode')),true);
assert.equal(await page.locator('html').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(2, 6, 23)');
assert.equal(await page.locator('.panel').first().evaluate(el=>getComputedStyle(el).borderRadius),'3px');
assert.equal(await page.locator('.dot').first().evaluate(el=>getComputedStyle(el).animationName),'status-pulse');
await page.emulateMedia({reducedMotion:'reduce'});
assert.equal(await page.locator('.dot').first().evaluate(el=>getComputedStyle(el).animationName),'none');
await page.emulateMedia({reducedMotion:'no-preference'});
await page.screenshot({path:'test-results/studio-desktop.png',fullPage:true});
const savedZoom=page.waitForResponse(response=>response.url().endsWith('/api/control') && response.request().method()==='POST');
await page.locator('#zoom').fill('1.2');
assert.equal((await savedZoom).status(),200);
await page.waitForFunction(async()=> (await (await fetch('/api/state')).json()).settings.zoom===1.2);
await page.reload();
await page.waitForFunction(()=>document.querySelector('#zoom').value==='1.2');
const response=await page.request.post(base+'/api/avatar',{headers:{'Content-Type':'application/octet-stream','X-Avatar-Name':'bad.vrm'},data:Buffer.from('invalid')});
assert.equal(response.status(),400);
await page.locator('#avatarFile').setInputFiles('assets/avatars/sample.vrm');
await page.waitForFunction(()=>document.querySelector('#avatarName').textContent==='sample.vrm');
await page.locator('#modelStatus').filter({hasText:'已加载'}).waitFor();
const output=await browser.newPage({viewport:{width:1280,height:720},deviceScaleFactor:1});
output.on('pageerror',error=>errors.push(error.message));
await output.goto(base+'/output');
await output.waitForTimeout(2500);
assert.equal(await output.locator('#app').isVisible(),false);
assert.equal(await output.locator('#cam').isVisible(),false);
assert.equal(await output.locator('#outputError').isVisible(),false);
assert.equal(await output.evaluate(()=>getComputedStyle(document.body).backgroundColor),'rgba(0, 0, 0, 0)');
await output.screenshot({path:'test-results/obs-output.png',omitBackground:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'test-results/studio-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.locator('#reset').click();
await page.waitForFunction(async()=> (await (await fetch('/api/state')).json()).settings.zoom===1);
assert.deepEqual(errors,[]);
console.log('PASS: model render/import, invalid file rejection, settings persistence, OBS transparency, mobile layout, no browser errors');
await browser.close();
