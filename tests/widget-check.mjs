import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const base=process.env.AVATAR_TEST_URL || 'http://127.0.0.1:8097';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:340,height:500}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/widget');
await page.waitForFunction(()=>document.documentElement.dataset.avatarReady==='true');
await page.waitForTimeout(1300);
assert.equal(await page.locator('#app').isVisible(),false);
assert.equal(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor),'rgba(0, 0, 0, 0)');
assert.equal(await page.locator('.pywebview-drag-region').count(),1);
assert.equal(await page.locator('#widgetTools,#widgetGrip,#outputError').count(),0);
assert.equal(await page.locator('body').innerText(),'');
await page.mouse.move(-20,-20);
await page.screenshot({path:'test-results/desktop-widget.png',omitBackground:true});
assert.deepEqual(errors,[]);
console.log('Widget view: transparent, full-body render, native drag region, controls, no JS errors: PASS');
await browser.close();
